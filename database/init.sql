-- ESQUEMA (coincide con las entidades JPA; necesario para que los INSERT
-- de este script funcionen en una base nueva y para ddl-auto=validate)
CREATE TABLE IF NOT EXISTS estudiantes (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni    VARCHAR(255) NOT NULL UNIQUE,
    nombre VARCHAR(255),
    estado VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS libros (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn                   VARCHAR(255) NOT NULL UNIQUE,
    titulo                 VARCHAR(255),
    autor                  VARCHAR(255),
    ejemplares_disponibles INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS prestamos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado         VARCHAR(255),
    fecha_prestamo DATE,
    estudiante_id  BIGINT REFERENCES estudiantes (id),
    libro_id       BIGINT REFERENCES libros (id)
);


